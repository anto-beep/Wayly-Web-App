"""Unified tool export surface (Export Consolidation, Jun 2026).

One PDF path and one email path shared by every result-payload tool, so
each tool's "Save as PDF" / "Email to self" affordance hits the same
server-rendered PDF pipeline instead of a bespoke per-tool endpoint.

Endpoints
---------
POST /api/public/exports/pdf     , body {tool, payload, person_name?} → PDF blob
POST /api/public/exports/email   , body {tool, payload, to?, person_name?} → {ok}

Supported ``tool`` values: contribution, budget, invoice, care-plan.
(Classification Self-Check, Provider Price Checker and Letters &
Follow-ups keep their own dedicated server-rendered PDF endpoints; this
router covers the tools that previously had no export affordance.)
"""
from __future__ import annotations

import base64
import logging
from io import BytesIO
from typing import Any, Callable, Dict, Optional

from fastapi import APIRouter, Depends, HTTPException, Request, Response
from pydantic import BaseModel, EmailStr, Field

logger = logging.getLogger("wayly.tool_exports")


class ExportPdfRequest(BaseModel):
    tool: str = Field(max_length=40)
    payload: dict
    person_name: Optional[str] = Field(default=None, max_length=120)


class ExportEmailRequest(BaseModel):
    tool: str = Field(max_length=40)
    payload: dict
    to: Optional[EmailStr] = None
    person_name: Optional[str] = Field(default=None, max_length=120)


# --- per-tool PDF adapters -------------------------------------------------

def _render_contribution(payload: dict, person_name: Optional[str]) -> bytes:
    from services.ce2_pdf import render_ce2_pdf
    return render_ce2_pdf(result=payload, person_name=person_name)


def _render_budget(payload: dict, person_name: Optional[str]) -> bytes:
    from services.budget_pdf import render_budget_pdf
    return render_budget_pdf(result=payload, person_name=person_name)


def _render_invoice(payload: dict, person_name: Optional[str]) -> bytes:
    from services.inv1_check_report_pdf import render_invoice_check_report
    invoice = {
        "provider_name": payload.get("provider_name"),
        "provider_abn": payload.get("provider_abn"),
        "invoice_date": payload.get("invoice_date"),
        "due_date": payload.get("due_date"),
        "document_shape": payload.get("document_shape"),
    }
    reconciliation = payload.get("reconciliation") or {}
    return render_invoice_check_report(invoice=invoice, reconciliation=reconciliation)


def _render_care_plan(payload: dict, person_name: Optional[str]) -> bytes:
    from services.care_plan_pdf import render_artefact_pdf
    buf = BytesIO()
    render_artefact_pdf(
        buf,
        plan={},
        extraction=payload.get("extraction") or {},
        findings=payload.get("findings") or [],
    )
    return buf.getvalue()


# tool → (renderer, filename_base, subject, paid-plan label)
_REGISTRY: Dict[str, tuple] = {
    "contribution": (_render_contribution, "contribution_estimate",
                     "Your Wayly Contribution Estimate", "Contribution Estimator"),
    "budget": (_render_budget, "budget_lifetime_cap",
               "Your Wayly Budget & Lifetime Cap", "Budget Calculator"),
    "invoice": (_render_invoice, "invoice_check_report",
                "Your Wayly Invoice Check", "Invoice Checker"),
    "care-plan": (_render_care_plan, "care_plan_review",
                  "Your Wayly Care Plan Review", "Care Plan Reviewer"),
}


