def build_tool_exports_router(
    *,
    require_paid_plan: Callable[..., Any],
    user_dep: Optional[Callable] = None,
) -> APIRouter:
    router = APIRouter(tags=["exports"])

    def _lookup(tool: str):
        entry = _REGISTRY.get(tool)
        if not entry:
            raise HTTPException(status_code=400, detail=f"Unknown export tool: {tool}")
        return entry

    async def _current_email(request: Request) -> Optional[str]:
        if user_dep is None:
            return None
        try:
            user = await user_dep(request)
            return (user or {}).get("email")
        except Exception:
            return None

    @router.post("/public/exports/pdf")
    async def export_pdf(body: ExportPdfRequest, request: Request, response: Response):
        renderer, fname_base, _subject, label = _lookup(body.tool)
        await require_paid_plan(request, response, label)
        try:
            pdf_bytes = renderer(body.payload, body.person_name)
        except Exception as e:
            logger.exception("export pdf render failed for %s: %s", body.tool, e)
            raise HTTPException(status_code=500, detail="PDF render failed")
        safe = (body.person_name or "wayly").replace(" ", "_").replace("/", "_")[:40] or "wayly"
        return Response(
            content=pdf_bytes,
            media_type="application/pdf",
            headers={
                "Content-Disposition": f'attachment; filename="{safe}_{fname_base}.pdf"',
                "Content-Length": str(len(pdf_bytes)),
            },
        )

    @router.post("/public/exports/email")
    async def export_email(body: ExportEmailRequest, request: Request, response: Response):
        renderer, fname_base, subject, label = _lookup(body.tool)
        await require_paid_plan(request, response, label)
        to = str(body.to) if body.to else await _current_email(request)
        if not to:
            raise HTTPException(status_code=400, detail="Please sign in to email this to yourself.")
        try:
            from email_service import _send, _sender  # type: ignore
        except Exception as e:
            logger.exception("email deps import failed: %s", e)
            raise HTTPException(status_code=503, detail="Email unavailable")
        try:
            pdf_bytes = renderer(body.payload, body.person_name)
        except Exception as e:
            logger.exception("export email render failed for %s: %s", body.tool, e)
            raise HTTPException(status_code=500, detail="PDF render failed")
        result = await _send({
            "from": _sender(),
            "to": [to],
            "subject": subject,
            "html": _email_html(subject),
            "attachments": [{
                "filename": f"{fname_base}.pdf",
                "content": base64.b64encode(pdf_bytes).decode("ascii"),
            }],
        })
        if not result.get("ok"):
            raise HTTPException(status_code=502, detail=f"Email failed: {result.get('reason')}")
        return {"ok": True, "id": result.get("id"), "mocked": bool(result.get("mocked"))}

    return router
